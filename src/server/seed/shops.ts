/** Shops carrying a category, cheapest tier first (regular → preferred → mall), then by id. */
export function shopsFor(category: string): Shop[] {
  const order = { regular: 0, preferred: 1, mall: 2 } as const;
  return SHOPS.filter((s) => SHOP_CATEGORIES[s.id]?.includes(category)).sort(
    (a, b) => order[a.tier] - order[b.tier] || a.id.localeCompare(b.id),
  );
}
