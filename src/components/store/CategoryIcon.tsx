export function CategoryIcon({ category, className = "" }: { category: string; className?: string }) {
  const c = categoryById(category);
  const Icon = (c && ICONS[c.icon]) || Package;
  return (
    <div className={`flex items-center justify-center ${c?.color ?? "bg-gray-100 text-gray-500"} ${className}`}>
      <Icon aria-hidden className="h-1/3 w-1/3" />
    </div>
  );
}
